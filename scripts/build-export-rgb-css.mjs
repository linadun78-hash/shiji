import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(projectRoot, 'src', 'content.css');
const targetPath = path.join(projectRoot, 'src', 'export-rgb.css');
const rootSelector = '#xhs-task-material-collector-root';
const exportRootSelector = `${rootSelector}.xmc-canvas-export-colors`;

const clamp = (value) => Math.min(1, Math.max(0, value));
const gamma = (value) => (
  value <= 0.0031308 ? 12.92 * value : 1.055 * (value ** (1 / 2.4)) - 0.055
);

function convertOklch(_match, lightness, chroma, hue, alpha = '1') {
  const radians = Number(hue) * Math.PI / 180;
  const a = Number(chroma) * Math.cos(radians);
  const b = Number(chroma) * Math.sin(radians);
  const lPrime = Number(lightness) + 0.3963377774 * a + 0.2158037573 * b;
  const mPrime = Number(lightness) - 0.1055613458 * a - 0.0638541728 * b;
  const sPrime = Number(lightness) - 0.0894841775 * a - 1.291485548 * b;
  const l = lPrime ** 3;
  const m = mPrime ** 3;
  const s = sPrime ** 3;
  const red = Math.round(clamp(gamma(4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s)) * 255);
  const green = Math.round(clamp(gamma(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s)) * 255);
  const blue = Math.round(clamp(gamma(-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s)) * 255);
  return `rgba(${red}, ${green}, ${blue}, ${Number(alpha)})`;
}

const source = fs.readFileSync(sourcePath, 'utf8');
const converted = source
  .replace(
    /oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+))?\s*\)/g,
    convertOklch,
  )
  .replaceAll(rootSelector, exportRootSelector);

const header = '/* Generated by scripts/build-export-rgb-css.mjs. Active only during image export. */\n';
fs.writeFileSync(targetPath, header + converted, 'utf8');
